import { chromium, devices } from 'playwright';
import { spawn } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
import { setTimeout as delay } from 'node:timers/promises';
import assert from 'node:assert/strict';

const server=spawn('python3',['-m','http.server','4173','--bind','127.0.0.1'],{stdio:'ignore'});
const url='http://127.0.0.1:4173';
async function waitForServer(){for(let i=0;i<40;i++){try{const response=await fetch(url+'/prototype/proportionsstadt.html');if(response.ok)return}catch{}await delay(250)}throw new Error('Lokaler Testserver nach 10 Sekunden nicht erreichbar')}
await mkdir('test-results/mobile',{recursive:true});
let browser;
const results=[];
try{
 await waitForServer();
 browser=await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-webgl']});
 for(const [label,device] of [['iphone',devices['iPhone 13']],['android',devices['Pixel 7']]]){
  const context=await browser.newContext({...device});
  const page=await context.newPage();
  const errors=[];
  page.on('console',message=>{if(message.type()==='error')console.error('['+label+'] browser console: '+message.text())});
  page.on('requestfailed',request=>console.error('['+label+'] request failed: '+request.url()+' '+(request.failure()?.errorText||'')));
  console.log('['+label+'] Akademie starten');
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(url+'/prototype/diagnoselabor-integration.html',{waitUntil:'domcontentloaded',timeout:20000});
  await page.getByRole('heading',{name:/Was möchtest du/}).waitFor();
  await page.getByRole('button',{name:/Starten/}).first().click();
  await page.locator('#game:not(.hide)').waitFor();
  await page.locator('#question').waitFor();
  assert.ok((await page.locator('#question').innerText()).length>5);
  await page.screenshot({path:'test-results/mobile/'+label+'-akademie.png',fullPage:true});
  console.log('['+label+'] Körperwerkstatt prüfen');
  await page.goto(url+'/prototype/koerperwerkstatt.html',{waitUntil:'domcontentloaded',timeout:20000});
  await page.getByRole('heading',{name:'Körperwerkstatt'}).waitFor();
  await page.getByRole('button',{name:'Höhe um eins vergrößern'}).click();
  assert.match(await page.locator('#dimensions').innerText(),/2 × 2 × 2/);
  await page.getByRole('button',{name:'Einen Einheitswürfel entfernen'}).click();
  assert.match(await page.locator('#cubeCount').innerText(),/7 von 8/);
  await page.locator('#answer').fill('8');
  await page.getByRole('button',{name:'Antwort prüfen'}).click();
  assert.match(await page.locator('#feedback').innerText(),/nicht vollständig/);
  await page.getByRole('button',{name:'Einen Einheitswürfel ergänzen'}).click();
  await page.locator('#answer').fill('8');
  await page.getByRole('button',{name:'Antwort prüfen'}).click();
  assert.match(await page.locator('#feedback').innerText(),/Richtig!/);
  await page.screenshot({path:'test-results/mobile/'+label+'-koerperwerkstatt.png',fullPage:true});
  console.log('['+label+'] Jahrgänge 7–10 prüfen');
  await page.goto(url+'/prototype/lernwelten-7-10.html',{waitUntil:'domcontentloaded',timeout:20000});
  await page.getByRole('button',{name:'Mission starten'}).first().click();
  await page.locator('#answer').fill('14');
  await page.getByRole('button',{name:'Prüfen'}).click();
  assert.match(await page.locator('#feedback').innerText(),/Denkfehler/);
  await page.locator('#answer').fill('20');
  await page.getByRole('button',{name:'Prüfen'}).click();
  assert.match(await page.locator('#feedback').innerText(),/Richtig!/);
  await page.screenshot({path:'test-results/mobile/'+label+'-lernwelten.png',fullPage:true});
  console.log('['+label+'] Proportionsstadt prüfen');
  await page.goto(url+'/prototype/proportionsstadt.html',{waitUntil:'domcontentloaded',timeout:20000});
  await page.getByRole('button',{name:'Ein Brückenfeld hinzufügen'}).click();
  await page.getByRole('button',{name:'Ein Brückenfeld hinzufügen'}).click();
  assert.match(await page.locator('#counter').innerText(),/5 Felder/);
  await page.locator('#answer').fill('20');
  await page.getByRole('button',{name:'Antwort prüfen'}).click();
  assert.match(await page.locator('#feedback').innerText(),/Richtig!/);
  await page.screenshot({path:'test-results/mobile/'+label+'-proportionsstadt.png',fullPage:true});
  // Fehlende externe 3D-Bibliothek darf die Mathematikmission nicht blockieren.
  const fallback=await context.newPage();
  await fallback.route('https://cdn.jsdelivr.net/**',route=>route.abort());
  await fallback.goto(url+'/prototype/proportionsstadt.html',{waitUntil:'domcontentloaded',timeout:20000});
  await fallback.waitForFunction(()=>document.getElementById('world3d')?.style.display==='none',null,{timeout:10000});
  assert.equal(await fallback.locator('svg#scene').isVisible(),true,'2D-Fallback muss sichtbar sein');
  await fallback.getByRole('button',{name:'Ein Brückenfeld hinzufügen'}).click();
  assert.match(await fallback.locator('#counter').innerText(),/4 Felder/);
  await fallback.close();
  console.log('['+label+'] Hauptwelt prüfen');
  await page.goto(url+'/',{waitUntil:'domcontentloaded',timeout:20000});
  await page.locator('#start').waitFor();
  await page.screenshot({path:'test-results/mobile/'+label+'-3d.png',fullPage:true});
  assert.equal(errors.length,0,'JavaScript-Fehler: '+errors.join(' | '));
  results.push(label+': Navigation, Aufgabenanzeige und JS ohne Fehler');
  await context.close();
 }
 console.log(results.join('\n'));
}finally{await browser?.close();server.kill();}
